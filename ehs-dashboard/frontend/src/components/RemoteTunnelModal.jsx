import { useState, useEffect } from 'react'
import {
  Globe,
  Clock,
  User,
  Copy,
  Check,
  ExternalLink,
  RefreshCw,
  Square,
  Play,
  ShieldCheck,
  AlertTriangle,
  Radio,
  X,
  Sparkles,
  Wifi,
  Trash2,
} from 'lucide-react'
import api from '../api'
import { useAuth } from '../context/AuthContext'

export default function RemoteTunnelModal({ isOpen, onClose }) {
  const { currentUser, isAdmin } = useAuth()
  const [tunnelData, setTunnelData] = useState(null)
  const [loading, setLoading] = useState(false)
  const [actionLoading, setActionLoading] = useState(false)
  const [selectedDuration, setSelectedDuration] = useState(30) // 20, 25, 30
  const [copied, setCopied] = useState(false)
  const [wifiCopied, setWifiCopied] = useState(false)
  const [secondsLeft, setSecondsLeft] = useState(0)
  const [msg, setMsg] = useState(null)
  const [wifiUrl, setWifiUrl] = useState('')

  // Fetch tunnel status from backend
  const fetchTunnelStatus = async () => {
    try {
      const res = await api.get('/system/tunnel/status')
      setTunnelData(res.data)
      if (res.data?.session?.seconds_remaining) {
        setSecondsLeft(res.data.session.seconds_remaining)
      } else {
        setSecondsLeft(0)
      }
    } catch (err) {
      console.error('Failed to load tunnel status', err)
    }
  }

  // Fetch system status for local wifi url
  const fetchSystemStatus = async () => {
    try {
      const res = await api.get('/system/status')
      if (res.data?.network?.wifi_url) {
        setWifiUrl(res.data.network.wifi_url)
      } else {
        setWifiUrl(`http://${window.location.hostname}:5174`)
      }
    } catch {
      setWifiUrl(`http://${window.location.hostname}:5174`)
    }
  }

  useEffect(() => {
    if (isOpen) {
      setLoading(true)
      Promise.all([fetchTunnelStatus(), fetchSystemStatus()]).finally(() => {
        setLoading(false)
      })

      // Polling every 5 seconds to keep multi-admin state synchronized
      const interval = setInterval(() => {
        fetchTunnelStatus()
      }, 5000)

      return () => clearInterval(interval)
    }
  }, [isOpen])

  // Live countdown timer ticking down every second
  useEffect(() => {
    if (secondsLeft <= 0) return

    const timer = setInterval(() => {
      setSecondsLeft((prev) => {
        if (prev <= 1) {
          // Re-fetch status when countdown reaches 0
          fetchTunnelStatus()
          return 0
        }
        return prev - 1
      })
    }, 1000)

    return () => clearInterval(timer)
  }, [secondsLeft])

  if (!isOpen) return null

  const session = tunnelData?.session
  const isActive = Boolean(tunnelData?.active && session?.url)
  const lastSession = tunnelData?.last_session

  const formatCountdown = (totalSeconds) => {
    if (totalSeconds <= 0) return '00:00'
    const mins = Math.floor(totalSeconds / 60)
    const secs = totalSeconds % 60
    return `${String(mins).padStart(2, '0')}:${String(secs).padStart(2, '0')}`
  }

  const formatTimestamp = (isoString) => {
    if (!isoString) return ''
    try {
      const d = new Date(isoString)
      return d.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' })
    } catch {
      return isoString
    }
  }

  // 1. Generate new tunnel
  const handleStartTunnel = async () => {
    setActionLoading(true)
    setMsg(null)
    try {
      const payload = {
        duration_minutes: selectedDuration,
        username: currentUser?.username || 'admin',
        full_name: currentUser?.full_name || 'Cluster EHS Admin',
      }
      const res = await api.post('/system/tunnel/start', payload)
      if (res.data?.session?.url) {
        setMsg({ type: 'success', text: `Remote tunnel active for ${selectedDuration} minutes!` })
      } else if (res.data?.status === 'already_active') {
        setMsg({
          type: 'warning',
          text: `Link already active! Generated by ${res.data.session?.created_by_name}. You can delete & regenerate below.`,
        })
      }
      await fetchTunnelStatus()
    } catch (err) {
      setMsg({ type: 'error', text: err.response?.data?.detail || 'Failed to generate remote tunnel.' })
    } finally {
      setActionLoading(false)
    }
  }

  // 2. Delete and regenerate tunnel
  const handleRegenerateTunnel = async () => {
    setActionLoading(true)
    setMsg(null)
    try {
      const payload = {
        duration_minutes: selectedDuration,
        username: currentUser?.username || 'admin',
        full_name: currentUser?.full_name || 'Cluster EHS Admin',
      }
      const res = await api.post('/system/tunnel/regenerate', payload)
      if (res.data?.session?.url) {
        setMsg({ type: 'success', text: `Old link replaced! New tunnel active for ${selectedDuration} minutes.` })
      }
      await fetchTunnelStatus()
    } catch (err) {
      setMsg({ type: 'error', text: err.response?.data?.detail || 'Failed to regenerate tunnel.' })
    } finally {
      setActionLoading(false)
    }
  }

  // 3. Stop tunnel
  const handleStopTunnel = async () => {
    setActionLoading(true)
    setMsg(null)
    try {
      await api.post(`/system/tunnel/stop?username=${encodeURIComponent(currentUser?.username || 'admin')}`)
      setMsg({ type: 'info', text: 'Remote tunnel terminated cleanly.' })
      await fetchTunnelStatus()
    } catch (err) {
      setMsg({ type: 'error', text: err.response?.data?.detail || 'Failed to stop tunnel.' })
    } finally {
      setActionLoading(false)
    }
  }

  const copyUrl = (urlToCopy) => {
    if (!urlToCopy) return
    navigator.clipboard.writeText(urlToCopy)
    setCopied(true)
    setTimeout(() => setCopied(false), 2000)
  }

  const copyWifi = () => {
    if (!wifiUrl) return
    navigator.clipboard.writeText(wifiUrl)
    setWifiCopied(true)
    setTimeout(() => setWifiCopied(false), 2000)
  }

  const durationPercentage = session?.duration_minutes
    ? Math.max(0, Math.min(100, (secondsLeft / (session.duration_minutes * 60)) * 100))
    : 0

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/60 p-4 backdrop-blur-xs overflow-y-auto">
      <div className="bg-white rounded-3xl shadow-2xl max-w-2xl w-full border border-slate-200 overflow-hidden animate-fadeIn">
        {/* HEADER */}
        <div className="bg-gradient-to-r from-slate-900 via-indigo-950 to-slate-900 text-white p-6 relative">
          <button
            onClick={onClose}
            className="absolute top-5 right-5 p-2 rounded-xl bg-white/10 hover:bg-white/20 text-white transition-colors cursor-pointer"
          >
            <X className="w-5 h-5" />
          </button>

          <div className="flex items-center gap-3">
            <div className="w-12 h-12 rounded-2xl bg-gradient-to-tr from-purple-500 to-indigo-500 flex items-center justify-center text-white shadow-lg">
              <Globe className="w-6 h-6 animate-pulse" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h2 className="text-lg font-black text-white tracking-tight">
                  Cloudflare Remote Access Portal
                </h2>
                <span className="text-[10px] uppercase font-bold tracking-wider px-2 py-0.5 rounded-full bg-emerald-500/20 text-emerald-300 border border-emerald-400/30">
                  EHS Admin Control
                </span>
              </div>
              <p className="text-xs text-slate-300 mt-0.5">
                Generate temporary, encrypted public links for external auditors, managers, and field staff.
              </p>
            </div>
          </div>
        </div>

        {/* NOTIFICATION MESSAGE */}
        {msg && (
          <div
            className={`px-6 py-2.5 text-xs font-semibold flex items-center justify-between ${
              msg.type === 'success'
                ? 'bg-emerald-50 text-emerald-800 border-b border-emerald-200'
                : msg.type === 'error'
                ? 'bg-rose-50 text-rose-800 border-b border-rose-200'
                : msg.type === 'warning'
                ? 'bg-amber-50 text-amber-800 border-b border-amber-200'
                : 'bg-indigo-50 text-indigo-800 border-b border-indigo-200'
            }`}
          >
            <span>{msg.text}</span>
            <button onClick={() => setMsg(null)} className="text-slate-400 hover:text-slate-600">
              <X className="w-3.5 h-3.5" />
            </button>
          </div>
        )}

        <div className="p-6 space-y-6 max-h-[80vh] overflow-y-auto">
          {/* SECTION 1: CLOUDFLARE REMOTE LINK STATUS */}
          {isActive ? (
            /* ACTIVE TUNNEL STATE */
            <div className="p-5 rounded-3xl bg-gradient-to-br from-emerald-50 via-teal-50 to-white border-2 border-emerald-400/80 shadow-sm space-y-4">
              <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 border-b border-emerald-200/80 pb-4">
                <div className="flex items-center gap-2.5">
                  <span className="relative flex h-3.5 w-3.5">
                    <span className="animate-ping absolute inline-flex h-full w-full rounded-full bg-emerald-400 opacity-75"></span>
                    <span className="relative inline-flex rounded-full h-3.5 w-3.5 bg-emerald-500"></span>
                  </span>
                  <div>
                    <div className="text-xs font-black uppercase tracking-wider text-emerald-950 flex items-center gap-1.5">
                      <span>Remote Link Active &amp; Encrypted</span>
                    </div>
                    <div className="text-[11px] text-emerald-800 font-medium">
                      Cloudflare Quick Tunnel TLS 1.3
                    </div>
                  </div>
                </div>

                {/* COUNTDOWN TIMER BADGE */}
                <div className="flex items-center gap-2 bg-emerald-950 text-white px-3.5 py-1.5 rounded-2xl shadow-xs">
                  <Clock className="w-4 h-4 text-emerald-400 animate-spin" style={{ animationDuration: '6s' }} />
                  <div className="text-right">
                    <div className="text-[9px] uppercase font-bold text-emerald-300 tracking-wider">
                      Expires In
                    </div>
                    <div className="font-mono text-sm font-black text-white tracking-widest leading-none">
                      {formatCountdown(secondsLeft)}
                    </div>
                  </div>
                </div>
              </div>

              {/* PROGRESS BAR */}
              <div className="w-full bg-emerald-200/70 h-2 rounded-full overflow-hidden">
                <div
                  className="bg-gradient-to-r from-emerald-500 to-teal-600 h-full transition-all duration-1000 ease-linear rounded-full"
                  style={{ width: `${durationPercentage}%` }}
                />
              </div>

              {/* WHO GENERATED & EXPIRY TIMESTAMP */}
              <div className="grid grid-cols-1 sm:grid-cols-3 gap-2.5 p-3 rounded-2xl bg-white/90 border border-emerald-200/80 text-xs shadow-2xs">
                <div>
                  <span className="text-[10px] font-bold text-slate-400 uppercase tracking-wider block">
                    Generated By
                  </span>
                  <span className="font-bold text-slate-800 flex items-center gap-1 truncate mt-0.5">
                    <User className="w-3.5 h-3.5 text-emerald-600 flex-shrink-0" />
                    <span className="truncate">{session?.created_by_name}</span>
                  </span>
                  <span className="text-[10px] text-slate-400 font-mono">@{session?.created_by_username}</span>
                </div>

                <div>
                  <span className="text-[10px] font-bold text-slate-400 uppercase tracking-wider block">
                    Created At
                  </span>
                  <span className="font-semibold text-slate-700 mt-0.5 block">
                    {formatTimestamp(session?.created_at)}
                  </span>
                  <span className="text-[10px] text-slate-400">Total: {session?.duration_minutes} Mins</span>
                </div>

                <div>
                  <span className="text-[10px] font-bold text-slate-400 uppercase tracking-wider block">
                    Auto-Expiry Time
                  </span>
                  <span className="font-bold text-rose-700 mt-0.5 block">
                    {formatTimestamp(session?.expires_at)}
                  </span>
                  <span className="text-[10px] text-emerald-700 font-semibold">Strict 30m Free Limit</span>
                </div>
              </div>

              {/* PUBLIC URL INPUT + ACTIONS */}
              <div className="space-y-1.5">
                <label className="text-[10px] font-extrabold uppercase tracking-wider text-slate-600">
                  Public Remote Access Link (Share with Team):
                </label>
                <div className="flex items-center gap-2 p-2 bg-white rounded-2xl border-2 border-emerald-300 shadow-2xs">
                  <input
                    type="text"
                    readOnly
                    value={session?.url || ''}
                    className="flex-1 bg-transparent text-xs font-mono font-black text-indigo-950 outline-none px-2 select-all"
                  />
                  <button
                    onClick={() => copyUrl(session?.url)}
                    className="px-3 py-1.5 rounded-xl bg-emerald-600 hover:bg-emerald-700 text-white font-bold text-xs flex items-center gap-1.5 shadow-xs transition-colors cursor-pointer"
                  >
                    {copied ? <Check className="w-3.5 h-3.5" /> : <Copy className="w-3.5 h-3.5" />}
                    <span>{copied ? 'Copied!' : 'Copy Link'}</span>
                  </button>
                  <a
                    href={session?.url}
                    target="_blank"
                    rel="noreferrer"
                    className="px-3 py-1.5 rounded-xl bg-slate-100 hover:bg-slate-200 text-slate-700 font-bold text-xs flex items-center gap-1 transition-colors"
                  >
                    <ExternalLink className="w-3.5 h-3.5" />
                    <span>Open</span>
                  </a>
                </div>
              </div>

              {/* QR CODE + ACTIONS ROW */}
              <div className="flex flex-col sm:flex-row items-center justify-between gap-4 pt-2">
                <div className="flex items-center gap-3">
                  <img
                    src={`https://api.qrserver.com/v1/create-qr-code/?size=90x90&data=${encodeURIComponent(
                      session?.url || ''
                    )}`}
                    alt="Tunnel QR Code"
                    className="w-16 h-16 rounded-xl border border-emerald-300 bg-white p-1 shadow-2xs"
                  />
                  <div className="text-left">
                    <div className="text-xs font-bold text-slate-800">Scan to Open on Phone</div>
                    <div className="text-[10px] text-slate-500">Fast access for plant site visitors</div>
                  </div>
                </div>

                {/* DELETE & REGENERATE / STOP BUTTONS */}
                <div className="flex items-center gap-2 flex-wrap">
                  <button
                    onClick={handleRegenerateTunnel}
                    disabled={actionLoading}
                    title="Delete present link and generate a fresh one immediately"
                    className="px-3.5 py-2 rounded-xl bg-indigo-600 hover:bg-indigo-700 active:bg-indigo-800 text-white font-bold text-xs flex items-center gap-1.5 shadow-xs transition-colors cursor-pointer disabled:opacity-50"
                  >
                    <RefreshCw className={`w-3.5 h-3.5 ${actionLoading ? 'animate-spin' : ''}`} />
                    <span>Delete &amp; Re-generate</span>
                  </button>

                  <button
                    onClick={handleStopTunnel}
                    disabled={actionLoading}
                    className="px-3 py-2 rounded-xl bg-rose-50 hover:bg-rose-100 text-rose-700 border border-rose-200 font-bold text-xs flex items-center gap-1.5 transition-colors cursor-pointer disabled:opacity-50"
                  >
                    <Square className="w-3.5 h-3.5" />
                    <span>Stop Link</span>
                  </button>
                </div>
              </div>
            </div>
          ) : (
            /* INACTIVE OR EXPIRED TUNNEL STATE */
            <div className="space-y-4">
              {/* Notice if last session expired */}
              {lastSession && (
                <div className="p-3.5 rounded-2xl bg-amber-50/80 border border-amber-200 text-amber-900 text-xs flex items-start gap-2.5">
                  <AlertTriangle className="w-4 h-4 text-amber-600 flex-shrink-0 mt-0.5" />
                  <div>
                    <div className="font-bold">
                      Previous Remote Link has Expired or was Terminated
                    </div>
                    <div className="text-[11px] text-amber-800 mt-0.5">
                      Generated by <strong>{lastSession.created_by_name}</strong> (@{lastSession.created_by_username}). Link expired at {formatTimestamp(lastSession.expires_at)}. You can now generate a new link below.
                    </div>
                  </div>
                </div>
              )}

              {/* GENERATE FORM */}
              <div className="p-6 rounded-3xl bg-slate-50 border border-slate-200/90 text-center space-y-4">
                <div className="w-14 h-14 rounded-2xl bg-indigo-100 text-indigo-700 mx-auto flex items-center justify-center shadow-inner">
                  <Globe className="w-7 h-7" />
                </div>

                <div>
                  <h3 className="text-base font-black text-slate-900">
                    No Active Remote Link
                  </h3>
                  <p className="text-xs text-slate-500 max-w-md mx-auto mt-1">
                    Select a safety duration and click below to start Cloudflare Quick Tunnel. A public URL will be created instantly and will auto-expire when time runs out.
                  </p>
                </div>

                {/* DURATION SELECTOR (20 - 30 MINS PER REQUIREMENT) */}
                <div className="max-w-md mx-auto space-y-2">
                  <label className="text-[11px] font-bold text-slate-700 uppercase tracking-wider block text-left">
                    Select Link Expiry Duration (Max 30 mins):
                  </label>
                  <div className="grid grid-cols-3 gap-2">
                    {[20, 25, 30].map((dur) => (
                      <button
                        key={dur}
                        type="button"
                        onClick={() => setSelectedDuration(dur)}
                        className={`py-2 px-3 rounded-2xl font-bold text-xs border transition-all cursor-pointer ${
                          selectedDuration === dur
                            ? 'bg-indigo-600 text-white border-indigo-700 shadow-sm ring-2 ring-indigo-300'
                            : 'bg-white text-slate-700 border-slate-200 hover:border-indigo-300'
                        }`}
                      >
                        <div className="text-sm font-black">{dur} Mins</div>
                        <div className="text-[9px] font-normal opacity-80">
                          {dur === 30 ? 'Free Tier Max' : dur === 20 ? 'Quick Share' : 'Standard'}
                        </div>
                      </button>
                    ))}
                  </div>
                </div>

                {/* GENERATE BUTTON */}
                <button
                  onClick={handleStartTunnel}
                  disabled={actionLoading}
                  className="px-6 py-3 rounded-2xl bg-gradient-to-r from-indigo-600 via-purple-600 to-indigo-700 hover:from-indigo-700 hover:to-purple-700 text-white font-extrabold text-sm inline-flex items-center gap-2 shadow-md hover:shadow-lg transition-all cursor-pointer disabled:opacity-50"
                >
                  <Play className={`w-4 h-4 ${actionLoading ? 'animate-spin' : ''}`} />
                  <span>
                    {actionLoading
                      ? 'Launching Cloudflare Tunnel...'
                      : `Generate ${selectedDuration}-Min Remote Link`}
                  </span>
                </button>
              </div>
            </div>
          )}

          {/* SECTION 2: PERMANENT LOCAL WI-FI PORTAL */}
          <div className="p-4 rounded-2xl bg-slate-50 border border-slate-200 space-y-2.5">
            <div className="flex items-center justify-between">
              <div className="flex items-center gap-2">
                <Wifi className="w-4 h-4 text-teal-600" />
                <span className="text-xs font-bold text-slate-800">
                  Direct Local Wi-Fi Access (No Expiry · Same Office / Plant Network)
                </span>
              </div>
              <span className="text-[10px] font-bold text-teal-700 bg-teal-100 px-2 py-0.5 rounded-full">
                Unlimited
              </span>
            </div>

            <div className="flex items-center gap-2 p-2 bg-white rounded-xl border border-slate-200 shadow-2xs">
              <input
                type="text"
                readOnly
                value={wifiUrl}
                className="flex-1 bg-transparent text-xs font-mono font-semibold text-slate-800 outline-none px-1"
              />
              <button
                onClick={copyWifi}
                className="px-2.5 py-1 rounded-lg bg-teal-700 hover:bg-teal-800 text-white font-bold text-xs flex items-center gap-1 transition-colors cursor-pointer"
              >
                {wifiCopied ? <Check className="w-3 h-3" /> : <Copy className="w-3 h-3" />}
                <span>{wifiCopied ? 'Copied' : 'Copy'}</span>
              </button>
            </div>
            <div className="text-[10px] text-slate-400">
              Devices connected to the same Wi-Fi router can access this address 24/7 without needing a Cloudflare link.
            </div>
          </div>
        </div>

        {/* FOOTER */}
        <div className="p-4 bg-slate-50 border-t border-slate-100 flex items-center justify-between text-xs text-slate-400">
          <div className="flex items-center gap-1.5">
            <ShieldCheck className="w-4 h-4 text-emerald-600" />
            <span>Zero open inbound ports &bull; Cloudflare Edge Protection</span>
          </div>
          <button
            onClick={onClose}
            className="px-4 py-1.5 rounded-xl bg-slate-200 hover:bg-slate-300 text-slate-700 font-bold text-xs transition-colors cursor-pointer"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  )
}
